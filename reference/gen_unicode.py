"""Generates src/symspell/_unicode_data.mojo from Python's unicodedata.

symspellpy relies on Python `str` methods (isalnum, isspace, isupper, isdigit,
isdecimal, lower, upper, capitalize). To match them exactly, we copy Python's
own data (docs/DECISIONS.md, D6).

Properties are stored as ranges: _PROP_STARTS[i] is the first codepoint of a run
of codepoints that all have the flags _PROP_FLAGS[i].

Case mappings are sorted key/value arrays. A value with bit 31 set points into
_CASE_MULTI: bits 8..30 are the offset, bits 0..7 the length.

The "cased" and "case-ignorable" classes drive Python's final sigma rule in
str.lower(). Python does not expose them, so we derive them from lower() itself:
for a codepoint c, "AcΣ".lower() ends with ς iff c is cased or case-ignorable,
and "AΣc".lower() has ς iff c is case-ignorable or not cased.
"""

import sys
import unicodedata

from _common import ROOT

OUT = ROOT / "src" / "symspell" / "_unicode_data.mojo"

ALNUM = 1
SPACE = 2
UPPER = 4
DIGIT = 8
DECIMAL = 16
CASED = 32
CASE_IGNORABLE = 64
SIGMA = "Σ"
FINAL_SIGMA = "ς"


def codepoints():
    for cp in range(0x110000):
        if not 0xD800 <= cp <= 0xDFFF:
            yield cp


def flags_of(c: str) -> int:
    flags = 0
    if c.isalnum():
        flags |= ALNUM
    if c.isspace():
        flags |= SPACE
    if c.isupper():
        flags |= UPPER
    if c.isdigit():
        flags |= DIGIT
    if c.isdecimal():
        flags |= DECIMAL | (unicodedata.decimal(c) << 8)
    if ("A" + c + SIGMA).lower()[-1] == FINAL_SIGMA:
        if ("A" + SIGMA + c).lower()[1] == FINAL_SIGMA:
            flags |= CASE_IGNORABLE
        else:
            flags |= CASED
    return flags


def property_ranges() -> tuple[list[int], list[int]]:
    starts, values = [], []
    previous = None
    for cp in range(0x110000):
        flags = 0 if 0xD800 <= cp <= 0xDFFF else flags_of(chr(cp))
        if flags != previous:
            starts.append(cp)
            values.append(flags)
            previous = flags
    return starts, values


def case_mapping(method: str, multi: list[int]) -> tuple[list[int], list[int]]:
    keys, values = [], []
    for cp in codepoints():
        c = chr(cp)
        mapped = getattr(c, method)()
        if mapped == c:
            continue
        keys.append(cp)
        if len(mapped) == 1:
            values.append(ord(mapped))
        else:
            values.append(0x80000000 | (len(multi) << 8) | len(mapped))
            multi.extend(ord(m) for m in mapped)
    return keys, values


def title_of(c: str) -> str:
    # capitalize() title-cases the first codepoint: "ǆ".capitalize() == "ǅ".
    return c.capitalize()


def mojo_array(name: str, dtype: str, values: list[int], doc: str) -> str:
    lines = [f"# {doc}", f"comptime {name}: Array[{dtype}, {len(values)}] = ["]
    row = []
    for v in values:
        row.append(f"0x{v:X}")
        if len(row) == 12:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("]")
    return "\n".join(lines)


def main() -> None:
    starts, flags = property_ranges()
    multi: list[int] = []
    lower_keys, lower_values = case_mapping("lower", multi)
    upper_keys, upper_values = case_mapping("upper", multi)
    # Title case of a single codepoint, via capitalize() on a one-codepoint string.
    title_keys, title_values = [], []
    for cp in codepoints():
        c = chr(cp)
        mapped = title_of(c)
        if mapped == c:
            continue
        title_keys.append(cp)
        if len(mapped) == 1:
            title_values.append(ord(mapped))
        else:
            title_values.append(0x80000000 | (len(multi) << 8) | len(mapped))
            multi.extend(ord(m) for m in mapped)

    header = f'''# Generated by reference/gen_unicode.py. Do not edit.
# Source: Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.
"""Unicode property and case mapping tables copied from Python's unicodedata."""

comptime UNICODE_VERSION = "{unicodedata.unidata_version}"

comptime FLAG_ALNUM: UInt16 = {ALNUM}
comptime FLAG_SPACE: UInt16 = {SPACE}
comptime FLAG_UPPER: UInt16 = {UPPER}
comptime FLAG_DIGIT: UInt16 = {DIGIT}
comptime FLAG_DECIMAL: UInt16 = {DECIMAL}
comptime FLAG_CASED: UInt16 = {CASED}
comptime FLAG_CASE_IGNORABLE: UInt16 = {CASE_IGNORABLE}
comptime MULTI_BIT: UInt32 = 0x80000000
'''
    parts = [
        header,
        mojo_array("PROP_STARTS", "UInt32", starts, "First codepoint of each property run."),
        mojo_array("PROP_FLAGS", "UInt16", flags, "Flags of each run; bits 8..11 hold the decimal digit value."),
        mojo_array("LOWER_KEYS", "UInt32", lower_keys, "Codepoints whose str.lower() differs."),
        mojo_array("LOWER_VALUES", "UInt32", lower_values, "str.lower() of LOWER_KEYS."),
        mojo_array("UPPER_KEYS", "UInt32", upper_keys, "Codepoints whose str.upper() differs."),
        mojo_array("UPPER_VALUES", "UInt32", upper_values, "str.upper() of UPPER_KEYS."),
        mojo_array("TITLE_KEYS", "UInt32", title_keys, "Codepoints whose title case differs."),
        mojo_array("TITLE_VALUES", "UInt32", title_values, "Title case of TITLE_KEYS."),
        mojo_array("CASE_MULTI", "UInt32", multi, "Multi-codepoint mappings."),
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    # The formatter would put every number on its own line.
    body = "\n\n".join(parts[1:])
    OUT.write_text(f"{parts[0]}\n# fmt: off\n{body}\n# fmt: on\n", encoding="utf-8")
    print(
        f"  {OUT.relative_to(ROOT)}: {len(starts)} property runs, {len(lower_keys)} lower, "
        f"{len(upper_keys)} upper, {len(title_keys)} title, {len(multi)} multi",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
